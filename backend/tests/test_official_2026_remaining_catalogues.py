class RemainingProspectus2026Tests(unittest.TestCase):
    def test_compulsory_catalogues(self):
        for code, expected in EXPECTED_COMPULSORY.items():
            with self.subTest(programme=code):
                self.assertEqual(set(PROGRAMME_MODULES[code]["compulsory"]), expected)

    def test_no_duplicate_module_links(self):
        for code in EXPECTED_COMPULSORY:
            with self.subTest(programme=code):
                compulsory = PROGRAMME_MODULES[code]["compulsory"]
                elective = PROGRAMME_MODULES[code]["elective"]
                self.assertEqual(len(compulsory), len(set(compulsory)))
                self.assertEqual(len(elective), len(set(elective)))
                self.assertFalse(set(compulsory) & set(elective))


